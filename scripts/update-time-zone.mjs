// Regenerates lib/data/time-zone.mjs, Winnipeg's UTC offsets, from the system time zone database
// (npm run tz:update). Winnigo converts every Winnipeg wall time with this checked-in table rather
// than the copies bundled with Node and PostgreSQL, which lag behind the law: tzdata 2026f records
// Manitoba's move to permanent UTC−5 on 2026-11-01, while Node 22 bundles 2026a. Run it after the
// operating system updates its tzdata, then review the diff like any other change.
//   npm run tz:update [-- --tzdir /path/to/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ZONE = 'America/Winnipeg';
const UNTIL_YEAR = 2100; // rules in the file's footer are expanded up to this year
const args = process.argv.slice(2);
const tzdir =
  (args.includes('--tzdir') && args[args.indexOf('--tzdir') + 1]) ||
  process.env.TZDIR ||
  '/usr/share/zoneinfo';

const bytes = readFileSync(join(tzdir, ZONE));
let version = 'unknown';
for (const file of ['+VERSION', 'tzdata.zi'])
  try {
    version =
      readFileSync(join(tzdir, file), 'utf8').match(/(?:version\s+)?(\d{4}[a-z])/)?.[1] || version;
    if (version !== 'unknown') break;
  } catch {
    /* not every system ships a version file */
  }

/** Parses a TZif file (RFC 8536): the 64-bit data block and the POSIX TZ footer. */
function parseTzif(buffer) {
  if (buffer.toString('ascii', 0, 4) !== 'TZif') throw Error('Not a TZif file');
  const counts = (at) => [0, 1, 2, 3, 4, 5].map((i) => buffer.readUInt32BE(at + 20 + i * 4));
  const [isutc, isstd, leap, time, type, chars] = counts(0);
  if (buffer[4] < 0x32) throw Error('TZif version 2 or later is required');
  const v1 = time * 5 + type * 6 + chars + leap * 8 + isstd + isutc;
  const start = 44 + v1;
  const [isutc2, isstd2, leap2, time2, type2, chars2] = counts(start);
  let at = start + 44;
  const times = [];
  for (let i = 0; i < time2; i++, at += 8) times.push(Number(buffer.readBigInt64BE(at)));
  const indexes = [...buffer.subarray(at, at + time2)];
  at += time2;
  const offsets = [];
  for (let i = 0; i < type2; i++, at += 6) offsets.push(buffer.readInt32BE(at));
  at += chars2 + leap2 * 12 + isstd2 + isutc2;
  const footer = buffer.toString('ascii', at).trim();
  return {
    transitions: times.map((t, i) => [t, offsets[indexes[i]]]),
    initial: offsets[0],
    footer,
  };
}

/** Offset in seconds east of UTC from a POSIX offset ("5", "-3:30"), which counts west. */
const posixOffset = (text) => {
  const [, sign, h, m = '0', s = '0'] = text.match(/^([+-]?)(\d+)(?::(\d+))?(?::(\d+))?$/);
  return (sign === '-' ? 1 : -1) * (+h * 3600 + +m * 60 + +s);
};

/** Expands a POSIX TZ string ("EST5", "CST6CDT,M3.2.0,M11.1.0") into transitions. */
function expandFooter(footer, fromYear) {
  const name = String.raw`(?:<[^>]+>|[A-Za-z]{3,})`;
  const offset = String.raw`[+-]?\d+(?::\d+){0,2}`;
  const rule = String.raw`M(\d+)\.(\d)\.(\d)(?:/([+-]?\d+(?::\d+){0,2}))?`;
  const match = footer.match(
    new RegExp(`^${name}(${offset})(?:${name}(${offset})?,${rule},${rule})?$`),
  );
  if (!match) throw Error(`Unsupported time zone rule: ${footer}`);
  const std = posixOffset(match[1]);
  if (!match[3]) return { transitions: [], final: std };
  const dst = match[2] ? posixOffset(match[2]) : std + 3600;
  const at = (year, month, week, weekday, time = '2') => {
    const first = new Date(Date.UTC(year, month - 1, 1)).getUTCDay();
    let day = 1 + ((weekday - first + 7) % 7) + (week - 1) * 7;
    const days = new Date(Date.UTC(year, month, 0)).getUTCDate();
    while (day > days) day -= 7;
    return Date.UTC(year, month - 1, day) / 1000 - posixOffset(time);
  };
  const transitions = [];
  for (let year = fromYear; year <= UNTIL_YEAR; year++) {
    transitions.push([at(year, +match[3], +match[4], +match[5], match[6]) - std, dst]);
    transitions.push([at(year, +match[7], +match[8], +match[9], match[10]) - dst, std]);
  }
  return { transitions: transitions.sort((a, b) => a[0] - b[0]), final: std };
}

const parsed = parseTzif(bytes);
const last = parsed.transitions.at(-1);
const lastYear = last ? new Date(last[0] * 1000).getUTCFullYear() : 1970;
const expanded = expandFooter(parsed.footer, lastYear + 1);
// Keep 1970 onwards, without repeated offsets.
const transitions = [];
let current = parsed.initial;
for (const [t, offset] of [...parsed.transitions, ...expanded.transitions]) {
  if (t < 0) {
    current = offset;
    continue;
  }
  if (offset !== (transitions.at(-1)?.[1] ?? current)) transitions.push([t, offset]);
}

const lines = [];
for (let i = 0; i < transitions.length; i += 4)
  lines.push(
    '    ' +
      transitions
        .slice(i, i + 4)
        .map(([t, o]) => `[${t}, ${o}]`)
        .join(', ') +
      ',',
  );
writeFileSync(
  new URL('../lib/data/time-zone.mjs', import.meta.url),
  `// Generated by scripts/update-time-zone.mjs from tzdata ${version}; do not edit by hand.
// [UTC seconds, offset seconds east of UTC] for ${ZONE}: each offset applies from its instant
// until the next. Before the first entry the offset is \`initial\`; rules after ${UNTIL_YEAR} are not covered.
export const WINNIPEG_TIME_ZONE = {
  zone: '${ZONE}',
  tzdata: '${version}',
  initial: ${current},
  transitions: [
${lines.join('\n')}
  ],
};
`,
);
console.log(
  `Wrote lib/data/time-zone.mjs from tzdata ${version}: ${transitions.length} transitions; ` +
    `current rule ${parsed.footer}.`,
);
